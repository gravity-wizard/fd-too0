import SwiftUI
import FDToo0Core

public struct WorldAtlasSheet: View {
    @Bindable var engine: GameEngine23
    @Environment(\.dismiss) private var dismiss
    @State private var jumpText: String = ""

    public init(engine: GameEngine23) {
        self.engine = engine
    }

    public var body: some View {
        NavigationStack {
            List {
                Section("Quick Jump & Daily #23 Seed") {
                    HStack {
                        TextField("Jump to Level (1 – 1023)", text: $jumpText)
                        Button("Launch") {
                            if let lvl = Int(jumpText.trimmingCharacters(in: .whitespaces)),
                               (1...1023).contains(lvl) {
                                engine.load(level: lvl)
                                dismiss()
                            }
                        }
                        .buttonStyle(.borderedProminent)
                    }

                    Button {
                        let comps = Calendar.current.dateComponents([.year, .month, .day], from: Date())
                        let seed = LevelSeedEngine.dailyChallengeLevelSeed(
                            year: comps.year ?? 2026,
                            month: comps.month ?? 11,
                            day: comps.day ?? 14
                        )
                        engine.load(level: 23, mode: .fdToo0, customSeed: seed)
                        dismiss()
                    } label: {
                        Label("Play Today's Daily #23 Gravitorium Seed", systemImage: "sparkles")
                    }
                }

                Section("10 Progressive Worlds (Levels 1 – 1,023)") {
                    ForEach(WorldChapter.allWorlds) { world in
                        VStack(alignment: .leading, spacing: 6) {
                            HStack {
                                Text("World \(world.id) • \(world.name)")
                                    .font(.headline)
                                Spacer()
                                Text("Lv \(world.startLevel)–\(world.endLevel)")
                                    .font(.caption.monospacedDigit())
                                    .foregroundStyle(.secondary)
                            }
                            Text("\(world.subtitle) — \(world.signatureMechanic)")
                                .font(.caption)
                                .foregroundStyle(.secondary)

                            HStack(spacing: 8) {
                                Button("Start #\(world.startLevel)") {
                                    engine.load(level: world.startLevel)
                                    dismiss()
                                }
                                .buttonStyle(.bordered)

                                let bossLvl = min(world.endLevel, ((world.startLevel - 1) / 23 + 1) * 23)
                                Button("Boss #\(bossLvl)") {
                                    engine.load(level: bossLvl)
                                    dismiss()
                                }
                                .buttonStyle(.bordered)
                            }
                            .padding(.top, 2)
                        }
                        .padding(.vertical, 4)
                    }
                }
            }
            .navigationTitle("FD_too0 Atlas (1,023)")
            .toolbar {
                ToolbarItem(placement: .confirmationAction) {
                    Button("Done") { dismiss() }
                }
            }
        }
    }
}

